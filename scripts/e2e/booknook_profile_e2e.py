"""Profile page e2e: stats, editing through BetterAuth, JWT carries the new name, route guard."""
import re, time, json
exec(open("scripts/e2e/booknook_phase6_e2e.py").read().split("stamp=str")[0])
stamp=str(int(time.time()))
with sync_playwright() as p:
    br=p.chromium.launch()
    anon=br.new_context().new_page(); anon.goto(BASE+"/profile"); anon.wait_for_url(re.compile(r"/login\?callbackUrl="))
    check("logged-out /profile -> login with callback", "profile" in anon.url)
    al=user_page(br,"Pat Owner",f"palice{stamp}@t.dev"); bo=user_page(br,"Pat Reader",f"pbob{stamp}@t.dev")
    ids=[call(al,"POST","/books",{"title":f"Profile Book {i} {stamp}","author":"A B","category":"Others","image":"https://i.ibb.co/x.png","description":"twenty plus characters of description here","totalCopies":2})["json"]["data"]["_id"] for i in range(2)]
    for i in ids: call(bo,"POST","/borrows",{"bookId":i,"returnDate":due()})
    rid=call(bo,"GET","/borrows")["json"]["data"][0]["_id"]; call(bo,"DELETE",f"/borrows/{rid}")
    bo.goto(BASE+"/profile"); bo.wait_for_selector("dt:has-text('Returned')")
    check("title is 'BookNook | My Profile'", bo.title()=="BookNook | My Profile", bo.title())
    check("shows name, email and member-since", bo.locator("h2:has-text('Pat Reader')").count()==1 and bo.locator(f"text=pbob{stamp}@t.dev").count()>=1 and bo.locator("text=Member since").count()==1)
    vals=[bo.locator(f"dl div:has(dt:text-is('{l}')) dd").inner_text() for l in ("Borrowed now","Returned","Books added")]
    check("stats from the real API: borrowed 1, returned 1, added 0", vals==["1","1","0"], str(vals))
    al.goto(BASE+"/profile"); al.wait_for_selector("dt:has-text('Books added')")
    check("owner stats: added 2, borrowed 0", al.locator("dl div:has(dt:text-is('Books added')) dd").inner_text()=="2" and al.locator("dl div:has(dt:text-is('Borrowed now')) dd").inner_text()=="0")
    check("email field is read-only", bo.get_attribute("#email","readonly") is not None)
    bo.fill("#name","P"); bo.fill("#photoUrl","not a url"); bo.click("button:has-text('Save changes')")
    check("profile validation errors shown", bo.locator("[role=alert]").count()>=2)
    bo.fill("#name","Pat Renamed"); bo.fill("#photoUrl","https://example.com/new.png"); bo.click("button:has-text('Save changes')")
    bo.wait_for_selector("h2:has-text('Pat Renamed')",timeout=10000)
    check("name updated on the page", True)
    bo.reload(); check("update persisted after reload", bo.locator("h2:has-text('Pat Renamed')").count()==1)
    tok=token(bo); payload=json.loads(__import__("base64").urlsafe_b64decode(tok.split(".")[1]+"=="))
    check("new JWT carries the updated name", payload["name"]=="Pat Renamed", payload["name"])
    nm=call(bo,"GET","/borrows")["json"]["data"]; check("API still authenticates after rename", len(nm)==2)
    bo.set_viewport_size({"width":390,"height":844}); bo.goto(BASE+"/profile"); bo.wait_for_selector("dt:has-text('Returned')")
    check("no horizontal overflow at 390px", bo.evaluate("document.documentElement.scrollWidth<=document.documentElement.clientWidth"))
    bo.screenshot(path="/tmp/profile-mobile.png",full_page=True)
    bo.set_viewport_size({"width":1440,"height":900}); bo.goto(BASE+"/profile"); bo.wait_for_selector("dt:has-text('Returned')"); bo.screenshot(path="/tmp/profile-desktop.png")
    br.close()
